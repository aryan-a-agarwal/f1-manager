const fs = require('fs');
const path = require('path');

const teamAchievements = JSON.parse(fs.readFileSync(path.join(__dirname, '../supabase/seed-data/f1-team-achievements.json'), 'utf8'));
const driverHistory = JSON.parse(fs.readFileSync(path.join(__dirname, '../supabase/seed-data/f1-driver-career-history.json'), 'utf8'));

let sql = `-- ==============================================================================
-- Migration: 20261026020000_f1_team_achievements_and_driver_career_history.sql
-- Description: Adds historical palmarès (all-time championships, wins, poles, podiums)
--              for all 11 F1 teams, and year-by-year driver career team history.
-- ==============================================================================

-- 1. Team achievements table
create table if not exists public.f1_team_achievements (
  id bigint generated by default as identity primary key,
  team_id bigint references public.f1_team_facts(id),
  team_slug text not null unique,
  constructors_championships integer not null default 0,
  drivers_championships integer not null default 0,
  race_wins integer not null default 0,
  podiums integer not null default 0,
  pole_positions integer not null default 0,
  fastest_laps integer not null default 0,
  first_win_year integer,
  last_win_year integer,
  last_championship_year integer,
  notable_achievements text,
  created_at timestamp with time zone not null default now()
);

alter table public.f1_team_achievements enable row level security;
drop policy if exists "Allow public select on f1_team_achievements" on public.f1_team_achievements;
create policy "Allow public select on f1_team_achievements" on public.f1_team_achievements for select to anon, authenticated using (true);
grant select on public.f1_team_achievements to anon, authenticated;

-- 2. Driver career history table (year-by-year stints)
create table if not exists public.f1_driver_career_history (
  id bigint generated by default as identity primary key,
  person_id bigint references public.people(id),
  driver_slug text not null,
  season integer not null,
  team_name text not null,
  team_slug text,
  starts integer not null default 0,
  wins integer not null default 0,
  podiums integer not null default 0,
  poles integer not null default 0,
  points numeric(7, 2) not null default 0,
  championship_position integer,
  titles_won integer not null default 0,
  created_at timestamp with time zone not null default now(),
  unique(driver_slug, season, team_name)
);

alter table public.f1_driver_career_history enable row level security;
drop policy if exists "Allow public select on f1_driver_career_history" on public.f1_driver_career_history;
create policy "Allow public select on f1_driver_career_history" on public.f1_driver_career_history for select to anon, authenticated using (true);
grant select on public.f1_driver_career_history to anon, authenticated;

-- 3. Seed team achievements
insert into public.f1_team_achievements (team_id, team_slug, constructors_championships, drivers_championships, race_wins, podiums, pole_positions, fastest_laps, first_win_year, last_win_year, last_championship_year, notable_achievements)
values
`;

const teamRows = teamAchievements.map(t => {
  const fw = t.first_win_year ? t.first_win_year : 'null';
  const lw = t.last_win_year ? t.last_win_year : 'null';
  const lc = t.last_championship_year ? t.last_championship_year : 'null';
  const note = t.notable_achievements.replace(/'/g, "''");
  return `  ((select id from public.f1_team_facts where slug = '${t.team_slug}'), '${t.team_slug}', ${t.constructors_championships}, ${t.drivers_championships}, ${t.race_wins}, ${t.podiums}, ${t.pole_positions}, ${t.fastest_laps}, ${fw}, ${lw}, ${lc}, '${note}')`;
});
sql += teamRows.join(',\n') + '\n';
sql += `on conflict (team_slug) do update set
  constructors_championships = excluded.constructors_championships,
  drivers_championships = excluded.drivers_championships,
  race_wins = excluded.race_wins,
  podiums = excluded.podiums,
  pole_positions = excluded.pole_positions,
  fastest_laps = excluded.fastest_laps,
  first_win_year = excluded.first_win_year,
  last_win_year = excluded.last_win_year,
  last_championship_year = excluded.last_championship_year,
  notable_achievements = excluded.notable_achievements;

-- 4. Update core teams table summary columns for consistency
`;

for (const t of teamAchievements) {
  const lw = t.last_win_year ? t.last_win_year : 'null';
  const lc = t.last_championship_year ? t.last_championship_year : 'null';
  sql += `update public.teams set
  constructors_championships = ${t.constructors_championships},
  drivers_championships = ${t.drivers_championships},
  all_time_wins = ${t.race_wins},
  all_time_podiums = ${t.podiums},
  all_time_poles = ${t.pole_positions},
  all_time_fastest_laps = ${t.fastest_laps},
  last_race_win_year = ${lw},
  last_championship_year = ${lc}
where slug = '${t.team_slug}';\n`;
}

sql += `
-- 5. Seed driver career history
insert into public.f1_driver_career_history (person_id, driver_slug, season, team_name, team_slug, starts, wins, podiums, poles, points, championship_position, titles_won)
values
`;

const driverRows = [];
for (const d of driverHistory) {
  for (const s of d.seasons) {
    const tSlug = s.team_slug ? `'${s.team_slug}'` : 'null';
    const pos = s.championship_position != null ? s.championship_position : 'null';
    const tName = s.team_name.replace(/'/g, "''");
    driverRows.push(`  ((select id from public.people where slug = '${d.driver_slug}'), '${d.driver_slug}', ${s.season}, '${tName}', ${tSlug}, ${s.starts}, ${s.wins}, ${s.podiums}, ${s.poles}, ${s.points}, ${pos}, ${s.titles_won})`);
  }
}
sql += driverRows.join(',\n') + '\n';
sql += `on conflict (driver_slug, season, team_name) do update set
  person_id = excluded.person_id,
  team_slug = excluded.team_slug,
  starts = excluded.starts,
  wins = excluded.wins,
  podiums = excluded.podiums,
  poles = excluded.poles,
  points = excluded.points,
  championship_position = excluded.championship_position,
  titles_won = excluded.titles_won;
`;

fs.writeFileSync(path.join(__dirname, '../supabase/migrations/20261026020000_f1_team_achievements_and_driver_career_history.sql'), sql);
console.log('SQL Migration generated! Driver records:', driverRows.length);
