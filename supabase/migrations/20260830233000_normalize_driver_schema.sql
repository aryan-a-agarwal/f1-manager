-- Preserve existing identity data before removing spreadsheet-derived fields.
update public.drivers
set
  first_name = coalesce(first_name, split_part(driver_name, ' ', 1)),
  last_name = coalesce(
    last_name,
    nullif(substr(driver_name, length(split_part(driver_name, ' ', 1)) + 2), '')
  ),
  date_of_birth = coalesce(date_of_birth, make_date(birth_year, 1, 1))
where driver_name is not null or birth_year is not null;

-- Link team names when the teams table uses the conventional name column.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'teams'
      and column_name = 'name'
  ) then
    execute $sql$
      update public.drivers d
      set team_id = t.id
      from public.teams t
      where d.team_id is null
        and lower(t.name) = lower(d.team)
    $sql$;
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.drivers'::regclass
      and conname = 'drivers_team_id_fkey'
  ) then
    alter table public.drivers
      add constraint drivers_team_id_fkey
      foreign key (team_id) references public.teams(id)
      on delete set null;
  end if;
end
$$;

create table if not exists public.driver_contracts (
  id bigint generated by default as identity primary key,
  driver_id bigint not null references public.drivers(id) on delete cascade,
  team_id bigint references public.teams(id) on delete set null,
  start_year integer,
  end_year integer,
  base_salary_usd_millions numeric(8, 2),
  bonus_clause_strength integer,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint driver_contracts_year_order check (
    end_year is null or start_year is null or end_year >= start_year
  ),
  constraint driver_contracts_bonus_range check (
    bonus_clause_strength is null or bonus_clause_strength between 0 and 100
  )
);

create table if not exists public.driver_career_stats (
  id bigint generated by default as identity primary key,
  driver_id bigint not null references public.drivers(id) on delete cascade,
  season integer,
  starts integer not null default 0,
  wins integer not null default 0,
  world_championships integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint driver_career_stats_nonnegative check (
    starts >= 0 and wins >= 0 and world_championships >= 0
  )
);

create unique index if not exists driver_career_stats_driver_season_idx
  on public.driver_career_stats (driver_id, season)
  nulls not distinct;

