-- Move existing spreadsheet values into their normalized tables.
insert into public.driver_contracts (
  driver_id,
  team_id,
  start_year,
  end_year,
  base_salary_usd_millions,
  bonus_clause_strength
)
select
  id,
  team_id,
  contract_start_year,
  contract_end_year_est,
  base_salary_usd_millions,
  bonus_clause_strength
from public.drivers
where contract_start_year is not null
   or contract_end_year_est is not null
   or base_salary_usd_millions is not null
   or bonus_clause_strength is not null;

insert into public.driver_career_stats (
  driver_id,
  starts,
  wins,
  world_championships
)
select
  id,
  coalesce(career_starts, 0),
  coalesce(career_wins, 0),
  coalesce(world_championships, 0)
from public.drivers
where career_starts is not null
   or career_wins is not null
   or world_championships is not null
on conflict (driver_id, season) do nothing;

